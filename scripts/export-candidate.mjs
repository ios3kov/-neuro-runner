import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const allowed = ['store.ts','gameStore.ts','components/FileSystem.tsx','components/AppContent.tsx','types.ts','package.json','package-lock.json'];
const path = process.argv[2];
if (!allowed.includes(path)) throw new Error('Unsupported source path');
let content = await readFile(path, 'utf8');
if (path === 'package-lock.json') content = JSON.stringify(JSON.parse(content));
console.log(`SOURCE_BEGIN ${path}`);
console.log(content);
console.log(`SOURCE_END ${path} SHA256 ${createHash('sha256').update(content).digest('hex')}`);
